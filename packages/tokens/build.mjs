function formatJsonNested({ dictionary }) {
  const tree = {};
  for (const t of dictionary.allTokens) {
    let node = tree;
    for (const seg of t.path.slice(0, -1)) {
      node[seg] ??= {};
      node = node[seg];
    }
    const leaf = { $value: t.$value, $type: t.$type };
    if (t.$description) leaf.$description = t.$description;
    node[t.path.at(-1)] = leaf;
  }
  return JSON.stringify(tree, null, 2) + '\n';
}

function formatJsonFlat({ dictionary }) {
  const flat = {};
  for (const t of dictionary.allTokens) {
    const entry = { value: t.$value, type: t.$type };
    if (t.$description) entry.description = t.$description;
    entry.original = t.original.$value;
    flat[displayPath(t)] = entry;
  }
  return JSON.stringify(flat, null, 2) + '\n';
}

