function dartColor(v) {
  const s = String(v).trim();
  if (s === 'transparent') return 'Color(0x00000000)';
  const c = parseColor(s);
  if (s.startsWith('#')) return `Color(0x${argbHex(c)})`;
  return `Color.fromRGBO(${c.r}, ${c.g}, ${c.b}, ${dbl(c.a, 3)})`;
}

function dartShadowLayer(l) {
  const c = parseColor(l.color);
  const args = [
    `color: Color(0x${argbHex(c)})`,
    `offset: Offset(${fmt(px(l.offsetX))}, ${fmt(px(l.offsetY))})`,
    `blurRadius: ${fmt(px(l.blur))}`,
  ];
  const spread = px(l.spread ?? '0px');
  if (spread !== 0) args.push(`spreadRadius: ${fmt(spread)}`);
  return `BoxShadow(${args.join(', ')})`;
}

const DART_WEIGHT = (w) => `FontWeight.w${w}`;

function formatDart({ dictionary }) {
  const out = [
    `// ${HEADER}`,
    '',
    "import 'package:flutter/material.dart';",
    '',
    '/// TP VPN design tokens (Light mode only).',
    '///',
    '/// Naming: token path `color.bg.canvas` → `TpTokens.colorBgCanvas`.',
    '/// Typography roles are `TextStyle` constants (fontSize, height, fontWeight,',
    '/// letterSpacing in logical px, tabular figures where the role requires it).',
    '/// Pair them with `fontFamily: TpTokens.fontFamilySans.first`.',
    'abstract final class TpTokens {',
  ];
  let first = true;
  for (const [group, tokens] of sectionsOf(dictionary.allTokens)) {
    if (!first) out.push('');
    first = false;
    out.push(`  // ── ${group} ${'─'.repeat(Math.max(2, 60 - group.length))}`);
    for (const t of tokens) {
      const name = camel(t.path);
      const doc = t.$description ? `  /// ${t.$description}\n` : '';
      const v = t.$value;
      switch (t.$type) {
        case 'color':
          out.push(`${doc}  static const Color ${name} = ${dartColor(v)};`);
          break;
        case 'dimension': {
          const { n, u } = parseUnit(v);
          if (u === 'em') {
            out.push(`${doc}  /// Unit: em (multiply by the font size).\n  static const double ${name} = ${dbl(n)};`);
          } else {
            out.push(`${doc}  static const double ${name} = ${fmt(n)};`);
          }
          break;
        }
        case 'number': {
          const isInt = Number.isInteger(v) && isGroup(t, 'z-index', 'grid');
          out.push(`${doc}  static const ${isInt ? 'int' : 'double'} ${name} = ${isInt ? v : dbl(v)};`);
          break;
        }
        case 'fontWeight':
          out.push(`${doc}  static const FontWeight ${name} = ${DART_WEIGHT(v)};`);
          break;
        case 'fontFamily':
          out.push(`${doc}  static const List<String> ${name} = [${v.map(sq).join(', ')}];`);
          break;
        case 'duration':
          out.push(`${doc}  static const Duration ${name} = Duration(milliseconds: ${fmt(ms(v))});`);
          break;
        case 'cubicBezier':
          out.push(`${doc}  static const Cubic ${name} = Cubic(${v.map((n) => dbl(n, 3)).join(', ')});`);
          break;
        case 'shadow': {
          const layers = Array.isArray(v) ? v : [v];
          const inset = layers.filter((l) => l.inset);
          if (inset.length) {
            const l = inset[0];
            const c = parseColor(l.color);
            out.push(
              `${doc}  /// CSS \`inset\` shadow — Flutter has no inset BoxShadow; draw it with` +
                ` \`Border.all(color: ${name}Color, width: ${name}Width)\`.`,
            );
            out.push(`  static const Color ${name}Color = Color(0x${argbHex(c)});`);
            out.push(`  static const double ${name}Width = ${fmt(px(l.spread ?? '1px'))};`);
          } else {
            out.push(
              `${doc}  static const List<BoxShadow> ${name} = [${layers.map(dartShadowLayer).join(', ')}];`,
            );
          }
          break;
        }
        case 'typography': {
          const size = px(v.fontSize);
          const lh = px(v.lineHeight);
          const ls = parseUnit(v.letterSpacing);
          const spacingPx = ls.u === 'em' ? ls.n * size : ls.n;
          const args = [
            `fontSize: ${fmt(size)}`,
            `height: ${dbl(lh / size)}`,
            `fontWeight: ${DART_WEIGHT(v.fontWeight)}`,
            `letterSpacing: ${fmt(spacingPx)}`,
          ];
          if (v.fontVariantNumeric === 'tabular-nums') {
            args.push('fontFeatures: [FontFeature.tabularFigures()]');
          }
          const notes = [];
          if (v.textTransform) notes.push(`text-transform: ${v.textTransform} (apply with toUpperCase())`);
          if (notes.length) out.push(`  /// ${notes.join('; ')}`);
          out.push(`${doc}  static const TextStyle ${name} = TextStyle(${args.join(', ')});`);
          break;
        }
        case 'string':
          out.push(`  // ${displayPath(t)} (CSS gradient, not representable as a const): ${v}`);
          break;
        default:
          throw new Error(`dart: unhandled $type "${t.$type}" at ${displayPath(t)}`);
      }
    }
  }
  out.push('}', '');
  return out.join('\n');
}

