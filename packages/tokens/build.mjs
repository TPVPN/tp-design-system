/** Number → shortest decimal string with at most `d` decimals (no trailing zeros). */
function fmt(n, d = 4) {
  if (!Number.isFinite(n)) throw new Error(`fmt(): non-finite number ${n}`);
  const s = n.toFixed(d);
  return s.includes('.') ? s.replace(/\.?0+$/, '') : s;
}

/** Number → decimal literal that always contains a '.', for Dart/Swift/Kotlin doubles. */
function dbl(n, d = 4) {
  const s = fmt(n, d);
  return s.includes('.') ? s : `${s}.0`;
}

/** "12px" | "-0.02em" | 12 → { n, u } */
function parseUnit(v) {
  if (typeof v === 'number') return { n: v, u: '' };
  const m = String(v).trim().match(/^(-?\d*\.?\d+)([a-z%]*)$/i);
  if (!m) throw new Error(`parseUnit(): cannot parse "${v}"`);
  return { n: parseFloat(m[1]), u: m[2] };
}

/** "12px" → 12 (throws if the unit is not px / unitless) */
function px(v) {
  const { n, u } = parseUnit(v);
  if (u !== 'px' && u !== '') throw new Error(`px(): expected px, got "${v}"`);
  return n;
}

/** "200ms" | "1.2s" → milliseconds (number) */
function ms(v) {
  const { n, u } = parseUnit(v);
  if (u === 's') return n * 1000;
  if (u === 'ms' || u === '') return n;
  throw new Error(`ms(): expected ms/s, got "${v}"`);
}

/** px → rem string (base 16), up to 4 decimals */
function rem(pxValue) {
  return `${fmt(pxValue / 16)}rem`;
}

/**
 * Parse a CSS colour into { r, g, b, a } (0–255 ints, a 0–1 float).
 * Supports #RGB, #RRGGBB, #RRGGBBAA, rgb()/rgba() (comma syntax) and "transparent".
 */
function parseColor(v) {
  const s = String(v).trim();
  if (s === 'transparent') return { r: 0, g: 0, b: 0, a: 0 };
  let m = s.match(/^#([0-9a-f]{3,8})$/i);
  if (m) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join('');
    const r = parseInt(h.slice(0, 2), 16);
    const g = parseInt(h.slice(2, 4), 16);
    const b = parseInt(h.slice(4, 6), 16);
    const a = h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1;
    return { r, g, b, a };
  }
  m = s.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*(\d*\.?\d+)\s*)?\)$/i);
  if (m) {
    return { r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : parseFloat(m[4]) };
  }
  throw new Error(`parseColor(): cannot parse "${v}"`);
}

const hex2 = (n) => Math.round(n).toString(16).padStart(2, '0').toUpperCase();
const argbHex = ({ r, g, b, a }) => `${hex2(a * 255)}${hex2(r)}${hex2(g)}${hex2(b)}`;

/** Normalise a CSS colour string for output (hex upper-case, rgba spacing tidy). */
function cssColor(v) {
  const s = String(v).trim();
  if (s === 'transparent') return s;
  if (s.startsWith('#')) return s.toUpperCase();
  const c = parseColor(s);
  return c.a === 1 ? `rgb(${c.r}, ${c.g}, ${c.b})` : `rgba(${c.r}, ${c.g}, ${c.b}, ${fmt(c.a, 3)})`;
}

/** ["Inter", "SF Pro Text", "sans-serif"] → Inter, 'SF Pro Text', sans-serif */
function cssFontFamily(list) {
  const arr = Array.isArray(list) ? list : [list];
  return arr.map((f) => (/[^a-z0-9_-]/i.test(f) ? `'${f}'` : f)).join(', ');
}

/** [a, b, c, d] → cubic-bezier(a, b, c, d) */
function cssBezier(arr) {
  return `cubic-bezier(${arr.map((n) => fmt(n)).join(', ')})`;
}

/** A single px length for shadow strings: "0px" → "0", "12px" → "12px" */
function shadowLen(v) {
  const n = px(v);
  return n === 0 ? '0' : `${fmt(n)}px`;
}

/** DTCG shadow (object | array | []) → CSS box-shadow value */
function cssShadow(value) {
  const layers = Array.isArray(value) ? value : [value];
  if (layers.length === 0) return 'none';
  return layers
    .map((l) => {
      const parts = [];
      if (l.inset) parts.push('inset');
      parts.push(shadowLen(l.offsetX), shadowLen(l.offsetY), shadowLen(l.blur));
      if (px(l.spread ?? '0px') !== 0) parts.push(shadowLen(l.spread));
      parts.push(cssColor(l.color));
      return parts.join(' ');
    })
    .join(', ');
}

/** Typography composite → ordered [suffix, cssValue] pairs */
function typographyParts(t) {
  const out = [
    ['font-family', cssFontFamily(t.fontFamily)],
    ['font-size', String(t.fontSize)],
    ['line-height', String(t.lineHeight)],
    ['font-weight', String(t.fontWeight)],
    ['letter-spacing', String(t.letterSpacing)],
  ];
  if (t.textTransform) out.push(['text-transform', String(t.textTransform)]);
  if (t.fontVariantNumeric) out.push(['font-variant-numeric', String(t.fontVariantNumeric)]);
  return out;
}

/** Scalar (non-typography) token → CSS value string */
function cssValue(token) {
  const v = token.$value;
  switch (token.$type) {
    case 'color':
      return cssColor(v);
    case 'shadow':
      return cssShadow(v);
    case 'cubicBezier':
      return cssBezier(v);
    case 'fontFamily':
      return cssFontFamily(v);
    case 'dimension':
    case 'duration':
    case 'string':
      return String(v);
    case 'fontWeight':
    case 'number':
      return String(v);
    default:
      throw new Error(`cssValue(): unhandled $type "${token.$type}" at ${token.path.join('.')}`);
  }
}

/**
 * Token → [[cssVarName, value], ...] with `prefix` (e.g. "--tp-").
 * Typography composites expand into several variables.
 */
function cssDeclarations(token, prefix) {
  const base = prefix + kebab(token.path);
  if (token.$type === 'typography') {
    return typographyParts(token.$value).map(([suffix, val]) => [`${base}-${suffix}`, val]);
  }
  return [[base, cssValue(token)]];
}

/* naming ------------------------------------------------------------------ */

const kebab = (p) => p.join('-');
const snake = (p) => p.join('_').replace(/-/g, '_');
function camel(p) {
  const words = p.join('-').split('-').filter(Boolean);
  return words
    .map((w, i) => (i === 0 ? w : w.charAt(0).toUpperCase() + w.slice(1)))
    .join('');
}
function pascal(p) {
  const c = camel(p);
  return c.charAt(0).toUpperCase() + c.slice(1);
}

const isGroup = (token, ...groups) => groups.includes(token.path[0]);
const isComponent = (token) => isGroup(token, ...COMPONENT_GROUPS);
const displayPath = (token) => token.path.join('.');

/** Group tokens by their first path segment, preserving order. */
function sectionsOf(tokens) {
  const map = new Map();
  for (const t of tokens) {
    const key = t.path[0];
    if (!map.has(key)) map.set(key, []);
    map.get(key).push(t);
  }
  return map;
}

const dq = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const sq = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

