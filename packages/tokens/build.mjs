function swiftColor(v) {
  const c = parseColor(v);
  const ch = (n) => dbl(n / 255, 4);
  return `UIColor(red: ${ch(c.r)}, green: ${ch(c.g)}, blue: ${ch(c.b)}, alpha: ${dbl(c.a, 3)})`;
}

