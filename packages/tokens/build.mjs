/** DTCG → Tokens Studio type, refined by path so Figma variable scopes are right. */
function figmaType(t) {
  const [g, s] = t.path;
  switch (t.$type) {
    case 'color':
      return 'color';
    case 'string':
      return g === 'gradient' ? 'color' : 'text';
    case 'dimension': {
      if (g === 'font' && s === 'size') return 'fontSizes';
      if (g === 'font' && s === 'line-height') return 'lineHeights';
      if (g === 'font' && s === 'letter-spacing') return 'letterSpacing';
      if (g === 'radius') return 'borderRadius';
      if (g === 'space') return 'spacing';
      if (g === 'border-width') return 'borderWidth';
      if (g === 'size') return 'sizing';
      if (isComponent(t)) {
        // Component-level dimensions: infer the Figma scope from the property name.
        const prop = t.path.slice(1).join('-');
        if (/radius/.test(prop)) return 'borderRadius';
        if (/padding|gap/.test(prop)) return 'spacing';
        if (/width$/.test(prop) && /ring|border/.test(prop)) return 'borderWidth';
        if (/height|width|size|thumb/.test(prop)) return 'sizing';
      }
      return 'dimension';
    }
    case 'fontFamily':
      return 'fontFamilies';
    case 'fontWeight':
      return 'fontWeights';
    case 'number':
      return g === 'opacity' ? 'opacity' : 'number';
    case 'duration':
    case 'cubicBezier':
      return 'other';
    case 'shadow':
      return 'boxShadow';
    case 'typography':
      return 'typography';
    default:
      throw new Error(`figma: unhandled $type "${t.$type}" at ${displayPath(t)}`);
  }
}

/** em letter-spacing → Figma percentage ("-0.02em" → "-2%"); references pass through. */
function figmaLetterSpacing(v) {
  if (typeof v !== 'string' || v.startsWith('{')) return v;
  const { n, u } = parseUnit(v);
  return u === 'em' ? `${fmt(n * 100)}%` : v;
}

function figmaShadowLayer(l) {
  return {
    x: shadowLen(l.offsetX).replace(/^0$/, '0'),
    y: shadowLen(l.offsetY),
    blur: shadowLen(l.blur),
    spread: shadowLen(l.spread ?? '0px'),
    color: cssColor(l.color),
    type: l.inset ? 'innerShadow' : 'dropShadow',
  };
}

function figmaValue(t) {
  const original = t.original.$value;
  const type = figmaType(t);
  const isRef = (x) => typeof x === 'string' && /^\{[^}]+\}$/.test(x.trim());
  switch (t.$type) {
    case 'fontFamily':
      return Array.isArray(original) ? original.join(', ') : original;
    case 'cubicBezier':
      return isRef(original) ? original : cssBezier(original);
    case 'duration':
      return original;
    case 'dimension':
      return type === 'letterSpacing' ? figmaLetterSpacing(original) : original;
    case 'shadow': {
      if (isRef(original)) return original;
      const layers = Array.isArray(original) ? original : [original];
      if (layers.length === 0) return 'none';
      const mapped = layers.map(figmaShadowLayer);
      return mapped.length === 1 ? mapped[0] : mapped;
    }
    case 'typography': {
      const o = original;
      const val = {
        fontFamily: o.fontFamily,
        fontWeight: o.fontWeight,
        fontSize: o.fontSize,
        lineHeight: o.lineHeight,
        letterSpacing: figmaLetterSpacing(o.letterSpacing),
      };
      if (o.textTransform) val.textCase = o.textTransform;
      return val;
    }
    default:
      return original;
  }
}

function formatFigma({ dictionary }) {
  const global = {};
  for (const t of dictionary.allTokens) {
    let node = global;
    for (const seg of t.path.slice(0, -1)) {
      node[seg] ??= {};
      node = node[seg];
    }
    const layers = t.$type === 'shadow' ? (Array.isArray(t.$value) ? t.$value : [t.$value]) : null;
    const leaf = {
      value: figmaValue(t),
      type: layers && layers.length === 0 ? 'other' : figmaType(t),
    };
    const desc = [];
    if (t.$description) desc.push(t.$description);
    if (t.$type === 'typography' && t.$value.fontVariantNumeric) desc.push(`font-variant-numeric: ${t.$value.fontVariantNumeric}`);
    if (desc.length) leaf.description = desc.join(' · ');
    node[t.path.at(-1)] = leaf;
  }
  const doc = { global, $themes: [], $metadata: { tokenSetOrder: ['global'] } };
  return JSON.stringify(doc, null, 2) + '\n';
}

