/* 2. dist/tailwind/theme.css                                                 */
/* ────────────────────────────────────────────────────────────────────────── */

function formatTailwind({ dictionary }) {
  const all = dictionary.allTokens;
  const by = (pred) => all.filter(pred);
  const theme = [];
  const root = [];
  const section = (arr, title) => arr.push('', `  /* ${title} */`);

  // Colours — primitives + semantics share the "color" root; drop the leading segment.
  section(theme, 'Colours — primitives');
  for (const t of by((t) => t.path[0] === 'color' && !SEMANTIC_COLOR_GROUPS.has(t.path[1]))) {
    theme.push(`  --color-${kebab(t.path.slice(1))}: ${cssColor(t.$value)};`);
  }
  section(theme, 'Colours — semantic');
  for (const t of by((t) => t.path[0] === 'color' && SEMANTIC_COLOR_GROUPS.has(t.path[1]))) {
    theme.push(`  --color-${kebab(t.path.slice(1))}: ${cssColor(t.$value)};`);
  }

  // Typography roles
  section(theme, 'Typography roles (text-<role>)');
  for (const t of by((t) => t.$type === 'typography' && t.path[0] === 'typography')) {
    const role = kebab(t.path.slice(1));
    const v = t.$value;
    const notes = [];
    if (v.textTransform) notes.push(`text-transform: ${v.textTransform}`);
    if (v.fontVariantNumeric) notes.push(`font-variant-numeric: ${v.fontVariantNumeric}`);
    if (notes.length) theme.push(`  /* ${role}: ${notes.join('; ')} */`);
    theme.push(`  --text-${role}: ${rem(px(v.fontSize))};`);
    theme.push(`  --text-${role}--line-height: ${rem(px(v.lineHeight))};`);
    theme.push(`  --text-${role}--font-weight: ${v.fontWeight};`);
    theme.push(`  --text-${role}--letter-spacing: ${v.letterSpacing};`);
  }

  // Font families / weights / tracking
  section(theme, 'Font families');
  for (const t of by((t) => t.path[0] === 'font' && t.path[1] === 'family')) {
    theme.push(`  --font-${kebab(t.path.slice(2))}: ${cssFontFamily(t.$value)};`);
  }
  section(theme, 'Font weights');
  for (const t of by((t) => t.path[0] === 'font' && t.path[1] === 'weight')) {
    theme.push(`  --font-weight-${kebab(t.path.slice(2))}: ${t.$value};`);
  }
  section(theme, 'Letter spacing');
  for (const t of by((t) => t.path[0] === 'font' && t.path[1] === 'letter-spacing')) {
    theme.push(`  --tracking-${kebab(t.path.slice(2))}: ${t.$value};`);
  }

  // Radius
  section(theme, 'Radius');
  for (const t of by((t) => t.path[0] === 'radius')) {
    theme.push(`  --radius-${kebab(t.path.slice(1))}: ${t.$value};`);
  }

  // Shadows
  section(theme, 'Elevation');
  for (const t of by((t) => t.path[0] === 'elevation')) {
    const layers = Array.isArray(t.$value) ? t.$value : [t.$value];
    const inset = layers.length > 0 && layers.every((l) => l.inset);
    const name = inset
      ? `--inset-shadow-${kebab(t.path.slice(1)).replace(/^inset-/, '')}`
      : `--shadow-${kebab(t.path.slice(1))}`;
    theme.push(`  ${name}: ${cssShadow(t.$value)};`);
  }

  // Motion
  section(theme, 'Motion');
  for (const t of by((t) => t.path[0] === 'easing')) {
    theme.push(`  --ease-${kebab(t.path.slice(1))}: ${cssBezier(t.$value)};`);
  }
  for (const t of by((t) => t.path[0] === 'duration')) {
    theme.push(`  --duration-${kebab(t.path.slice(1))}: ${t.$value};`);
  }

  // Layout
  section(theme, 'Breakpoints & containers');
  for (const t of by((t) => t.path[0] === 'breakpoint')) {
    theme.push(`  --breakpoint-${kebab(t.path.slice(1))}: ${t.$value};`);
  }
  for (const t of by((t) => t.path[0] === 'container')) {
    theme.push(`  --container-${kebab(t.path.slice(1))}: ${t.$value};`);
  }

  // Spacing scale + named sizes (spacing namespace → h-*, w-*, size-*, p-*, gap-* …)
  section(theme, 'Spacing (4pt grid) & named sizes');
  theme.push('  --spacing: 0.25rem;');
  for (const t of by((t) => t.path[0] === 'size' && t.path[1] !== 'logo')) {
    const rest = t.path.slice(1).map((s) => (s === 'connection-button' ? 'connection' : s));
    theme.push(`  --spacing-${kebab(rest)}: ${t.$value};`);
  }

  // :root extras — non-namespaced tokens and component tokens
  section(root, 'Gradients');
  for (const t of by((t) => t.path[0] === 'gradient')) {
    root.push(`  --gradient-${kebab(t.path.slice(1))}: ${t.$value};`);
  }
  section(root, 'Z-index');
  for (const t of by((t) => t.path[0] === 'z-index')) {
    root.push(`  --z-index-${kebab(t.path.slice(1))}: ${t.$value};`);
  }
  section(root, 'Opacity');
  for (const t of by((t) => t.path[0] === 'opacity')) {
    root.push(`  --opacity-${kebab(t.path.slice(1))}: ${t.$value};`);
  }
  section(root, 'Logo ratios & minimum sizes');
  for (const t of by((t) => t.path[0] === 'logo')) {
    root.push(`  --logo-${kebab(t.path.slice(1))}: ${t.$value};`);
  }
  for (const t of by((t) => t.path[0] === 'size' && t.path[1] === 'logo')) {
    root.push(`  --logo-${kebab(t.path.slice(2))}: ${t.$value};`);
  }
  section(root, 'Border widths');
  for (const t of by((t) => t.path[0] === 'border-width')) {
    root.push(`  --border-width-${kebab(t.path.slice(1))}: ${t.$value};`);
  }
  section(root, 'Component tokens (resolved)');
  for (const t of by(isComponent)) {
    for (const [name, value] of cssDeclarations(t, '--tp-')) root.push(`  ${name}: ${value};`);
  }

  return [
    `/* ${HEADER} */`,
    '/* Tailwind CSS v4 theme for TP VPN. Light mode only. */',
    '',
    '@theme {',
    ...theme.slice(1),
    '}',
    '',
    ':root {',
    ...root.slice(1),
    '}',
    '',
  ].join('\n');
}

