function formatCss({ dictionary }) {
  const lines = [`/* ${HEADER} */`, '', ':root {'];
  for (const [group, tokens] of sectionsOf(dictionary.allTokens)) {
    lines.push(`  /* ${group} */`);
    for (const t of tokens) {
      for (const [name, value] of cssDeclarations(t, '--tp-')) lines.push(`  ${name}: ${value};`);
    }
    lines.push('');
  }
  if (lines.at(-1) === '') lines.pop();
  lines.push('}', '');
  return lines.join('\n');
}

